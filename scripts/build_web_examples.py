"""Bundle examples/*.s into web/js/examples.js for the datapath visualizer.

Browsers refuse fetch() from file:// pages, so the example programs are
embedded in a script instead. Run this after editing an example; the test
suite fails if the bundle is out of date.

    python scripts/build_web_examples.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXAMPLES = ROOT / "examples"
OUTPUT = ROOT / "web" / "js" / "examples.js"

#: Menu titles, in display order; other examples follow alphabetically.
TITLES = {
    "course_demo.s": "Course demo (Phase 2 C program)",
    "fibonacci.s": "Fibonacci numbers",
    "bubble_sort.s": "Bubble sort",
}


def render() -> str:
    order = list(TITLES)
    paths = sorted(EXAMPLES.glob("*.s"), key=lambda p: (order.index(p.name) if p.name in order else len(order), p.name))
    examples = []
    for path in paths:
        source = path.read_text(encoding="utf-8").replace("\r\n", "\n")
        examples.append({"name": path.name, "title": TITLES.get(path.name, path.stem), "source": source})
    body = json.dumps(examples, indent=2, ensure_ascii=False)
    return (
        "// Generated by scripts/build_web_examples.py from examples/*.s - do not edit.\n"
        f"window.SYMRISC_EXAMPLES = {body};\n"
    )


def main() -> None:
    OUTPUT.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
